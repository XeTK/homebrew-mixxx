#!/usr/bin/env python3
"""Rewrite Casks/mixxx-fork.rb from the fork's signed update manifest.

The update feed (https://mixxx.xetk.co.uk/updates/latest.json) is signed with
minisign by the fork's publish workflow; this checks that signature against
the key the Mixxx app itself trusts before using anything in the manifest.
Then it takes the macOS build and writes the cask for it.

  update_cask.py --manifest latest.json --signature latest.json.minisig \
      --out Casks/mixxx-fork.rb

Prints "changed" or "unchanged". Exits non-zero, and writes nothing, if the
signature or the manifest is not what it should be.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

FEED_URL = "https://mixxx.xetk.co.uk/updates"
PLATFORM = "macos-arm64"
# The public key the app trusts: kPublicKey in xetk/mixxx
# src/updates/updatepublickey.h. Change both together.
PUBLIC_KEY = "RWQ8Ou6PToqFXjplJxqkeygZdATrHe7TXe8Nkk6yr/rz8HwLUJ1R22lD"

_VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(?:-[a-z0-9.]+)?$")
_SHA256 = re.compile(r"^[0-9a-f]{64}$")

CASK = """\
# Generated by tools/update_cask.py from {feed}/latest.json.
# Do not edit by hand: the next update overwrites it.
cask "mixxx-fork" do
  version "{version},{build}"
  sha256 "{sha256}"

  url "{feed}/mixxx-b#{{version.csv.second}}-{platform}.dmg"
  name "Mixxx (xetk accessibility fork)"
  desc "DJ software with screen reader support and other accessibility work"
  homepage "{feed}/index.html"

  livecheck do
    url "{feed}/latest.json"
    strategy :json do |json|
      "#{{json["version"]}},#{{json["build"]}}"
    end
  end

  conflicts_with cask: "mixxx"
  depends_on arch: :arm64
  depends_on :macos

  app "Mixxx.app"

  caveats <<~EOS
    This build is not notarized, so macOS blocks its first launch. Open it
    once, then choose Open Anyway in System Settings > Privacy & Security, or:
      xattr -dr com.apple.quarantine /Applications/Mixxx.app

    It shares its settings and library with official Mixxx; don't run both
    at once.
  EOS
end
"""


class FeedError(Exception):
    pass


def verify(manifest, signature, public_key=PUBLIC_KEY, run=subprocess.run):
    """Raise FeedError unless minisign accepts the signature."""
    result = run(
        ["minisign", "-V", "-q", "-P", public_key, "-m", str(manifest), "-x", str(signature)],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise FeedError("signature check failed: " + (result.stderr or result.stdout).strip())


def cask_fields(manifest_text):
    """The cask's version, build and sha256 from a manifest, validated."""
    try:
        manifest = json.loads(manifest_text)
    except json.JSONDecodeError as error:
        raise FeedError(f"manifest is not JSON: {error}") from error
    if not isinstance(manifest, dict):
        raise FeedError("manifest is not an object")
    version = manifest.get("version")
    build = manifest.get("build")
    if not isinstance(version, str) or not _VERSION.match(version):
        raise FeedError(f"unexpected version {version!r}")
    if not isinstance(build, int) or isinstance(build, bool) or build <= 0:
        raise FeedError(f"unexpected build {build!r}")
    entry = (manifest.get("platforms") or {}).get(PLATFORM)
    if not isinstance(entry, dict):
        raise FeedError(f"manifest has no {PLATFORM} build")
    sha256 = entry.get("sha256")
    if not isinstance(sha256, str) or not _SHA256.match(sha256):
        raise FeedError(f"unexpected sha256 {sha256!r}")
    # The cask builds the URL from the build number; it must be the one the
    # manifest names, or the checksum would be for a different file.
    expected = f"{FEED_URL}/mixxx-b{build}-{PLATFORM}.dmg"
    if entry.get("url") != expected:
        raise FeedError(f"url {entry.get('url')!r} is not {expected!r}")
    return {"version": version, "build": build, "sha256": sha256}


def render(fields):
    return CASK.format(feed=FEED_URL, platform=PLATFORM, **fields)


def update(manifest, signature, out, run=subprocess.run):
    """Verify, then write the cask if it changed. Returns True if it did."""
    verify(manifest, signature, run=run)
    text = render(cask_fields(Path(manifest).read_text(encoding="utf-8")))
    out = Path(out)
    if out.exists() and out.read_text(encoding="utf-8") == text:
        return False
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return True


def main(argv=None, run=subprocess.run):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", maxsplit=1)[0])
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--signature", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        changed = update(args.manifest, args.signature, args.out, run=run)
    except FeedError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print("changed" if changed else "unchanged")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
